
public class ListNode {
    private String name;
    private double avg;
    private ListNode link;
    public void setName(String n)
    {	name = n;	}
    public void setAvg(double a)
    {	avg = a;	}
    public void setLink(ListNode l)
    {	link = l;	}
    public String getName()
    {	return name;	}
    public double getAvg()
    {	return avg;	}
    public ListNode getLink()
    {	return link;	}
}
